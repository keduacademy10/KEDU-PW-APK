/* SUBJECT PAGE BACK BUTTON — RETURN TO BATCHES PAGE         */
/* ========================================================= */

document.addEventListener(
    "click",
    function(event){

        const backButton =
            event.target.closest(
                "#subjects-back-btn"
            );

        if(!backButton){
            return;
        }

        event.preventDefault();
        event.stopPropagation();


        /* ------------------------------------------------- */
        /* Close any active detail page                      */
        /* ------------------------------------------------- */

        const classDetailPage =
            document.getElementById(
                "class-detail-page"
            );


        if(classDetailPage){

            classDetailPage.classList.remove(
                "active"
            );

            classDetailPage.style.display =
                "none";

            classDetailPage.setAttribute(
                "aria-hidden",
                "true"
            );

        }


        /* ------------------------------------------------- */
        /* RETURN TO BATCHES PAGE                            */
        /* ------------------------------------------------- */

        const batchesPage =
            document.getElementById(
                "class-detail-page"
            );


        /* ------------------------------------------------- */
        /* Hide all pages                                    */
        /* ------------------------------------------------- */

        document
            .querySelectorAll(
                ".page"
            )
            .forEach(
                page => {

                    page.style.display =
                        "none";

                    page.classList.remove(
                        "active"
                    );

                    page.setAttribute(
                        "aria-hidden",
                        "true"
                    );

                }
            );


        /* ------------------------------------------------- */
        /* Show batches page                                 */
        /* ------------------------------------------------- */

        if(batchesPage){

            batchesPage.style.display =
                "flex";

            batchesPage.classList.add(
                "active"
            );

            batchesPage.setAttribute(
                "aria-hidden",
                "false"
            );

        }


        /* ------------------------------------------------- */
        /* Reset batches page scroll                         */
        /* ------------------------------------------------- */

        requestAnimationFrame(
            function(){

                if(batchesPage){

                    batchesPage.scrollTop =
                        0;

                }

                window.scrollTo({

                    top: 0,
                    left: 0,
                    behavior: "instant"

                });

            }
        );

    },
    true
);


