/* SUBJECT CARD CLICK                                        */
/* ========================================================= */

document.addEventListener(
    "click",
    function(event){

        const card =
            event.target.closest(
                ".subject-card"
            );


        if(!card){

            return;

        }


        const subjectName =
            card.dataset.subject || "";


        if(!subjectName){

            return;

        }


        const normalizedSubject =
            subjectName
                .toLowerCase()
                .trim();


        let subjectKey =
            "other";


        if(
            normalizedSubject.includes(
                "physical chemistry"
            )
        ){

            subjectKey =
                "physical-chemistry";

        }

        else if(
            normalizedSubject.includes(
                "inorganic chemistry"
            )
        ){

            subjectKey =
                "inorganic-chemistry";

        }

        else if(
            normalizedSubject.includes(
                "organic chemistry"
            )
        ){

            subjectKey =
                "organic-chemistry";

        }

        else if(
            normalizedSubject.includes(
                "physics"
            )
        ){

            subjectKey =
                "physics";

        }

        else if(
            normalizedSubject.includes(
                "chemistry"
            )
        ){

            subjectKey =
                "chemistry";

        }

        else if(
            normalizedSubject.includes(
                "biology"
            )
        ){

            subjectKey =
                "biology";

        }

        else if(
            normalizedSubject.includes(
                "botany"
            )
        ){

            subjectKey =
                "botany";

        }

        else if(
            normalizedSubject.includes(
                "zoology"
            )
        ){

            subjectKey =
                "zoology";

        }

        else if(
            normalizedSubject === "maths" ||
            normalizedSubject.includes(
                "maths "
            ) ||
            normalizedSubject.includes(
                "mathematics"
            )
        ){

            subjectKey =
                "mathematics";

        }

        else if(
            normalizedSubject.includes(
                "science"
            )
        ){

            subjectKey =
                "science";

        }


        /* ============================================== */
        /* SAVE CURRENT SUBJECT                           */
        /* ============================================== */

        window.currentSubject =
    subjectName;


        if (typeof currentBatch !== "undefined") {
    currentBatch =
        card.dataset.batch || currentBatch;
}

        /* ============================================== */
        /* OPEN CHAPTER PAGE                              */
        /* ============================================== */

        if(
            typeof openChapterPage ===
            "function"
        ){

            openChapterPage(

                subjectKey,

                subjectName,

                card.dataset.class,

                card.dataset.batch

            );

        }

        else{

            console.error(
                "KEDU PW: openChapterPage() not found."
            );

        }

    }
);


