function highlightSubject(subjectTitle){

    const cards =
        document.querySelectorAll(
            ".subject-card"
        );

    cards.forEach(card => {

        card.classList.remove(
            "active-search"
        );

    });


    const target =
        Array.from(cards).find(card => {

            const title =
                card.querySelector(
                    ".subject-title"
                );

            return (
                title &&
                title.textContent
                    .trim()
                    .toLowerCase() ===
                subjectTitle
                    .trim()
                    .toLowerCase()
            );

        });


    if(!target){

        return;

    }


    target.classList.add(
        "active-search"
    );


    target.scrollIntoView({

        behavior:"smooth",

        block:"center"

    });


    setTimeout(() => {

        target.classList.remove(
            "active-search"
        );

    },2500);

}


